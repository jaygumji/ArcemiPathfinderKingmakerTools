using System;
using System.Buffers.Binary;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace Arcemi.Models.Warhammer40KDarkHeresy
{
    internal sealed record OwlFieldRange(int LengthOffset, int PayloadOffset, int Length)
    {
        public int End => checked(PayloadOffset + Length);
        public int PrefixLength => PayloadOffset - LengthOffset;
    }

    internal sealed record OwlFactList(OwlFieldRange Manager, OwlFieldRange List, int Count)
    {
        public int CountOffset => List.PayloadOffset + 7;
    }

    internal sealed record OwlWritableType(ushort Id, IReadOnlyList<byte> FieldIds);

    internal sealed class W40KDHOwlFeatureWriter
    {
        internal static readonly IReadOnlyDictionary<string, string[]> Layout = new Dictionary<string, string[]> {
            ["Kingmaker.UnitLogic.Feature"] = new[] { "m_ComponentsData", "m_Components", "m_Sources", "m_ChildrenFacts",
                "UniqueId", "m_Blueprint", "IsActive", "ChildOf", "m_ParentContext", "m_Context", "Rank", "IsTemporary",
                "Param", "IgnorePrerequisites", "DisabledBecauseOfPrerequisites" },
            ["System.Collections.Generic.List`1[[Kingmaker.EntitySystem.EntityFactComponent"] = Array.Empty<string>(),
            ["Kingmaker.EntitySystem.EntityFactComponentDelegate`1+ComponentRuntime[[Kingmaker.EntitySystem.Entities.BaseUnitEntity"] =
                new[] { "SourceBlueprintComponentName" },
            ["Kingmaker.EntitySystem.EntityFactRef"] = new[] { "EntityId", "FactId" },
            ["Kingmaker.UnitLogic.Mechanics.MechanicsContext"] = new[] { "m_OwnerRef", "m_CasterRef", "m_FactRef", "m_Ability",
                "m_Source", "m_ClickedTarget", "Blueprint", "Direction", "DisableFx", "PropertiesConverter" },
            ["Kingmaker.EntitySystem.Entities.Base.EntityRef`1[[Kingmaker.EntitySystem.Entities.MechanicEntity"] = new[] { "Id" },
            ["Kingmaker.EntitySystem.EntityFactRef`1[[Kingmaker.UnitLogic.Mechanics.Facts.MechanicEntityFact"] = new[] { "EntityId", "FactId" },
            ["Kingmaker.UnitLogic.Mechanics.MechanicsContext+SourceInfo"] = new[] { "m_CasterRef", "m_FactRef", "ClickedTarget",
                "CastPosition", "Blueprint", "Ability" },
            ["Kingmaker.Utility.TargetWrapper"] = new[] { "EntityRef", "m_Point", "m_Orientation" },
            ["UnityEngine.Vector3"] = new[] { "x", "y", "z" },
            ["Kingmaker.UnitLogic.Levelup.Obsolete.Blueprints.Selection.FeatureParam"] = new[] { "Blueprint", "WeaponCategory", "StatType" },
        };

        internal const string AttributeType = "Kingmaker.UnitLogic.Progression.Features.Advancements.BlueprintAttributeAdvancement";
        internal const string SkillType = "Kingmaker.UnitLogic.Progression.Features.Advancements.BlueprintSkillAdvancement";
        private static readonly byte[] Null = { 0 };

        private readonly IReadOnlyDictionary<string, OwlWritableType> _types;
        private readonly HashSet<uint> _reservedIds = new();
        private uint _nextId;

        public W40KDHOwlFeatureWriter(IReadOnlyDictionary<string, OwlWritableType> types, byte[] original)
        {
            _types = types;
            // Reserve a range beyond the IDs normally generated by the game, including IDs found in earlier Arcemi edits.
            _nextId = checked((uint)original.Length + 1);
            for (var i = 0; i <= original.Length - 5; i++) {
                if (original[i] is 1 or 2) {
                    var id = BinaryPrimitives.ReadUInt32LittleEndian(original.AsSpan(i + 1, 4));
                    if (id >= _nextId) _reservedIds.Add(id);
                }
            }
        }

        private uint NextId()
        {
            while (_reservedIds.Contains(_nextId)) _nextId++;
            return _nextId++;
        }

        public byte[] Create(string owner, string id, string blueprint, string component, int rank, int step)
        {
            var blueprintObjectId = NextId();
            var blueprintObject = Object(step == 5 ? AttributeType : SkillType, blueprintObjectId, String(blueprint));
            var componentObject = Object("Kingmaker.EntitySystem.EntityFactComponentDelegate`1+ComponentRuntime[[Kingmaker.EntitySystem.Entities.BaseUnitEntity",
                String(component));
            var components = List("System.Collections.Generic.List`1[[Kingmaker.EntitySystem.EntityFactComponent", componentObject);
            var child = Object("Kingmaker.EntitySystem.EntityFactRef", String(null), String(null));
            var context = Object("Kingmaker.UnitLogic.Mechanics.MechanicsContext",
                EntityRef(owner), EntityRef(owner), FactRef(owner, id), Null,
                Object("Kingmaker.UnitLogic.Mechanics.MechanicsContext+SourceInfo", EntityRef(null), FactRef(null, null), Null, Null, Null, Null),
                Object("Kingmaker.Utility.TargetWrapper", EntityRef(owner), Null, Null), Reference(blueprintObjectId),
                Object("UnityEngine.Vector3", new byte[] { 8, 0, 0, 0, 0, 0 }, new byte[] { 8, 0, 0, 0, 0, 0 },
                    new byte[] { 8, 0, 0, 0, 0, 0 }), Boolean(false), Null);
            var absentEnum = new byte[] { 13, 128, 0, 0 };
            var param = Object("Kingmaker.UnitLogic.Levelup.Obsolete.Blueprints.Selection.FeatureParam", Null, absentEnum, absentEnum);

            return Object("Kingmaker.UnitLogic.Feature", Null, components, Null, Null, String(id), blueprintObject,
                Boolean(true), child, Null, context, Int32(rank), Boolean(false), param, Boolean(true), Boolean(false));
        }

        public static byte[] Insert(byte[] source, OwlFieldRange scene, IReadOnlyList<(OwlFactList Facts, byte[][] Items)> added)
        {
            var changes = new List<(int Start, int End, byte[] Value)>();
            var sceneGrowth = 0;
            foreach (var (facts, items) in added) {
                var itemBytes = items.SelectMany(item => item).ToArray();
                var listLength = checked(facts.List.Length + itemBytes.Length);
                var listPrefix = Length(listLength);
                var managerLength = checked(facts.Manager.Length + itemBytes.Length + listPrefix.Length - facts.List.PrefixLength);
                var managerPrefix = Length(managerLength);
                sceneGrowth = checked(sceneGrowth + managerLength - facts.Manager.Length + managerPrefix.Length - facts.Manager.PrefixLength);

                changes.Add((facts.Manager.LengthOffset, facts.Manager.PayloadOffset, managerPrefix));
                changes.Add((facts.List.LengthOffset, facts.List.PayloadOffset, listPrefix));
                var count = new byte[sizeof(int)];
                BinaryPrimitives.WriteInt32LittleEndian(count, checked(facts.Count + items.Length));
                changes.Add((facts.CountOffset, facts.CountOffset + sizeof(int), count));
                changes.Add((facts.List.End, facts.List.End, itemBytes));
            }
            changes.Add((scene.LengthOffset, scene.PayloadOffset, Length(checked(scene.Length + sceneGrowth))));

            using var output = new MemoryStream();
            var position = 0;
            foreach (var change in changes.OrderBy(change => change.Start)) {
                if (change.Start < position) throw new InvalidDataException("Overlapping OWL fact edits.");
                output.Write(source.AsSpan(position, change.Start - position));
                output.Write(change.Value);
                position = change.End;
            }
            output.Write(source.AsSpan(position));
            return output.ToArray();
        }

        private byte[] EntityRef(string owner) =>
            Object("Kingmaker.EntitySystem.Entities.Base.EntityRef`1[[Kingmaker.EntitySystem.Entities.MechanicEntity", String(owner));

        private byte[] FactRef(string owner, string id) =>
            Object("Kingmaker.EntitySystem.EntityFactRef`1[[Kingmaker.UnitLogic.Mechanics.Facts.MechanicEntityFact", String(owner), String(id));

        private byte[] Object(string type, params byte[][] fields) => Object(type, NextId(), fields);

        private byte[] Object(string type, uint id, params byte[][] fields)
        {
            using var stream = new MemoryStream();
            using var writer = new BinaryWriter(stream);
            writer.Write((byte)2);
            writer.Write(id);
            writer.Write(_types[type].Id);
            for (var i = 0; i < fields.Length; i++) {
                writer.Write(_types[type].FieldIds[i]);
                writer.Write7BitEncodedInt(fields[i].Length);
                writer.Write(fields[i]);
            }
            return stream.ToArray();
        }

        private byte[] List(string type, byte[] item)
        {
            using var stream = new MemoryStream();
            using var writer = new BinaryWriter(stream);
            writer.Write((byte)2);
            writer.Write(NextId());
            writer.Write(_types[type].Id);
            writer.Write(1);
            writer.Write(item);
            return stream.ToArray();
        }

        private static byte[] String(string value)
        {
            using var stream = new MemoryStream();
            using var writer = new BinaryWriter(stream, Encoding.UTF8);
            writer.Write((ushort)12);
            writer.Write(value is not null);
            if (value is not null) writer.Write(value);
            return stream.ToArray();
        }

        private static byte[] Boolean(bool value) => new byte[] { 11, 0, value ? (byte)1 : (byte)0 };

        private static byte[] Int32(int value)
        {
            var bytes = new byte[6];
            bytes[0] = 4;
            BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(2), value);
            return bytes;
        }

        private static byte[] Reference(uint id)
        {
            var bytes = new byte[5];
            bytes[0] = 1;
            BinaryPrimitives.WriteUInt32LittleEndian(bytes.AsSpan(1), id);
            return bytes;
        }

        private static byte[] Length(int length)
        {
            using var stream = new MemoryStream();
            using var writer = new BinaryWriter(stream);
            writer.Write7BitEncodedInt(length);
            return stream.ToArray();
        }
    }
